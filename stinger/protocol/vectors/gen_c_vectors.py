"""Convert vectors.json into golden_vectors.h for the C codec tests.

This is a data conversion only; it never calls a codec. Run from anywhere:

    python protocol/vectors/gen_c_vectors.py
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
JSON_PATH = HERE / "vectors.json"
HEADER_PATH = HERE / "golden_vectors.h"


def c_bytes(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[] = {{{body}}};"


def mac_bytes(text: str) -> bytes:
    return bytes.fromhex(text.replace(":", ""))


def message_initializer(ident: str, msg: dict, arrays: list[str]) -> str:
    kind = msg["type"]
    head = f".type = STINGER_MSG_{kind}, .seq = {msg['seq']}"
    match kind:
        case "FRAME":
            rgb = bytes.fromhex(msg["rgb"])
            rgb_ref = "NULL"
            if rgb:
                arrays.append(c_bytes(f"{ident}_rgb", rgb))
                rgb_ref = f"{ident}_rgb"
            body = f".u.frame = {{{msg['bar_id']}, {len(rgb) // 3}, {rgb_ref}}}"
        case "SHOW":
            body = f".u.show = {{{msg['frame_seq']}}}"
        case "CONFIG":
            body = f".u.config = {{{msg['bar_id']}, STINGER_KEY_{msg['key']}, {msg['value']}}}"
        case "CONFIG_MAC":
            arrays.append(c_bytes(f"{ident}_mac", mac_bytes(msg["mac"])))
            body = f".u.config_mac = {{{ident}_mac, STINGER_KEY_{msg['key']}, {msg['value']}}}"
        case "PING" | "PONG":
            body = f".u.ping = {{{msg['t_ms']}u}}"
        case "HELLO":
            arrays.append(c_bytes(f"{ident}_mac", mac_bytes(msg["mac"])))
            body = (
                f".u.hello = {{{msg['bar_id']}, {ident}_mac, {msg['led_count']}, "
                f"{msg['fw_version']}, {msg['rssi']}}}"
            )
        case "STATS":
            body = (
                f".u.stats = {{{msg['rx_packets']}u, {msg['crc_errors']}u, {msg['tx_failures']}u}}"
            )
        case _:
            raise ValueError(f"unknown message type {kind}")
    return f"{{{head}, {body}}}"


def render(vectors: dict) -> str:
    arrays: list[str] = []
    cobs_rows, packet_rows, wire_rows, bad_rows = [], [], [], []

    for i, case in enumerate(vectors["cobs"]):
        arrays.append(c_bytes(f"gv_cobs_{i}_dec", bytes.fromhex(case["decoded"])))
        arrays.append(c_bytes(f"gv_cobs_{i}_enc", bytes.fromhex(case["encoded"])))
        cobs_rows.append(
            f"    {{gv_cobs_{i}_dec, sizeof(gv_cobs_{i}_dec), "
            f"gv_cobs_{i}_enc, sizeof(gv_cobs_{i}_enc)}},"
        )

    for case in vectors["packets"]:
        ident = f"gv_{case['name']}"
        arrays.append(c_bytes(f"{ident}_packet", bytes.fromhex(case["packet"])))
        arrays.append(c_bytes(f"{ident}_wire", bytes.fromhex(case["wire"])))
        init = message_initializer(ident, case["message"], arrays)
        packet_rows.append(
            f'    {{"{case["name"]}", {ident}_packet, sizeof({ident}_packet), '
            f"{ident}_wire, sizeof({ident}_wire), {init}}},"
        )

    for case in vectors["invalid_wire"]:
        ident = f"gv_bad_wire_{case['name']}"
        arrays.append(c_bytes(ident, bytes.fromhex(case["wire"])))
        wire_rows.append(
            f'    {{"{case["name"]}", {ident}, sizeof({ident}), STINGER_ERR_{case["error"]}}},'
        )

    for case in vectors["invalid_packets"]:
        ident = f"gv_bad_packet_{case['name']}"
        arrays.append(c_bytes(ident, bytes.fromhex(case["packet"])))
        bad_rows.append(
            f'    {{"{case["name"]}", {ident}, sizeof({ident}), STINGER_ERR_{case["error"]}}},'
        )

    crc = vectors["crc_check"]
    lines = [
        "/* Generated by gen_c_vectors.py from vectors.json. Do not edit. */",
        "#ifndef GOLDEN_VECTORS_H",
        "#define GOLDEN_VECTORS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        '#include "stinger_proto.h"',
        "",
        "typedef struct {",
        "    const uint8_t *decoded;",
        "    size_t decoded_len;",
        "    const uint8_t *encoded;",
        "    size_t encoded_len;",
        "} golden_cobs_t;",
        "",
        "typedef struct {",
        "    const char *name;",
        "    const uint8_t *packet;",
        "    size_t packet_len;",
        "    const uint8_t *wire;",
        "    size_t wire_len;",
        "    stinger_msg_t msg;",
        "} golden_packet_t;",
        "",
        "typedef struct {",
        "    const char *name;",
        "    const uint8_t *bytes;",
        "    size_t len;",
        "    stinger_err_t error;",
        "} golden_invalid_t;",
        "",
        f'#define GOLDEN_CRC_INPUT "{crc["ascii"]}"',
        f"#define GOLDEN_CRC_VALUE 0x{crc['crc']:04x}",
        "",
        *arrays,
        "",
        "static const golden_cobs_t golden_cobs[] = {",
        *cobs_rows,
        "};",
        "",
        "static const golden_packet_t golden_packets[] = {",
        *packet_rows,
        "};",
        "",
        "static const golden_invalid_t golden_invalid_wire[] = {",
        *wire_rows,
        "};",
        "",
        "static const golden_invalid_t golden_invalid_packets[] = {",
        *bad_rows,
        "};",
        "",
        "#define GOLDEN_COUNT(a) (sizeof(a) / sizeof((a)[0]))",
        "",
        "#endif /* GOLDEN_VECTORS_H */",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    HEADER_PATH.write_text(render(json.loads(JSON_PATH.read_text())))
    print(f"wrote {HEADER_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
