"""Convert bar_scenarios.json into a C header for the bar firmware's native tests.

Messages are encoded with the Python codec, which the golden vectors already pin down.

    python tests/gen_bar_scenarios.py
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from stinger_proto import encode_packet  # noqa: E402
from vectors import message_from_json  # noqa: E402

JSON_PATH = HERE / "bar_scenarios.json"
HEADER_PATH = HERE.parent / "firmware" / "bar" / "test" / "test_bar" / "bar_scenarios.h"


def c_bytes(data: bytes) -> str:
    return "{" + ", ".join(f"0x{b:02x}" for b in data) + "}"


def render(doc: dict) -> str:
    s = doc["settings"]
    arrays, scenario_rows = [], []
    for si, sc in enumerate(doc["scenarios"]):
        steps = []
        for ti, step in enumerate(sc["steps"]):
            ident = f"sc{si}_step{ti}"
            if "send" in step:
                packet = encode_packet(step["send"]["seq"], message_from_json(step["send"]))
                arrays.append(f"static const uint8_t {ident}[] = {c_bytes(packet)};")
                steps.append(f"    {{STEP_SEND, {step['at']}u, {ident}, sizeof({ident}), 0}},")
            elif "expect" in step:
                pixels = bytes.fromhex(step["expect"])
                arrays.append(f"static const uint8_t {ident}[] = {c_bytes(pixels)};")
                steps.append(
                    f"    {{STEP_EXPECT_PIXELS, {step['at']}u, {ident}, sizeof({ident}), 0}},"
                )
            else:
                hello = step["expect_hello"]
                hello_id = -1 if hello is None else hello
                steps.append(f"    {{STEP_EXPECT_HELLO, {step['at']}u, NULL, 0, {hello_id}}},")
        arrays.append(f"static const scenario_step_t sc{si}_steps[] = {{")
        arrays.extend(steps)
        arrays.append("};")
        mac = bytes.fromhex(sc["mac"].replace(":", ""))
        scenario_rows.append(
            f'    {{"{sc["name"]}", {sc["bar_id"]}, {c_bytes(mac)}, sc{si}_steps, '
            f"sizeof(sc{si}_steps) / sizeof(sc{si}_steps[0])}},"
        )
    lines = [
        "/* Generated by tests/gen_bar_scenarios.py from tests/bar_scenarios.json. Do not edit. */",
        "#ifndef BAR_SCENARIOS_H",
        "#define BAR_SCENARIOS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"#define SCENARIO_LED_COUNT {s['led_count']}",
        f"#define SCENARIO_HARD_LIMIT {s['hard_limit']}",
        f"#define SCENARIO_FAILSAFE_TIMEOUT_MS {s['failsafe_timeout_ms']}",
        f"#define SCENARIO_FAILSAFE_FADE_MS {s['failsafe_fade_ms']}",
        f"#define SCENARIO_HELLO_INTERVAL_MS {s['hello_interval_ms']}",
        f"#define SCENARIO_FW_VERSION {s['fw_version']}",
        "",
        "typedef enum { STEP_SEND, STEP_EXPECT_PIXELS, STEP_EXPECT_HELLO } step_kind_t;",
        "",
        "typedef struct {",
        "    step_kind_t kind;",
        "    uint32_t at;",
        "    const uint8_t *bytes; /* packet to send, or expected R G B */",
        "    size_t len;",
        "    int hello_id; /* STEP_EXPECT_HELLO: expected bar_id, or -1 for no HELLO */",
        "} scenario_step_t;",
        "",
        "typedef struct {",
        "    const char *name;",
        "    uint8_t bar_id;",
        "    uint8_t mac[6];",
        "    const scenario_step_t *steps;",
        "    size_t step_count;",
        "} scenario_t;",
        "",
        *arrays,
        "",
        "static const scenario_t scenarios[] = {",
        *scenario_rows,
        "};",
        "",
        "#endif /* BAR_SCENARIOS_H */",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    HEADER_PATH.write_text(render(json.loads(JSON_PATH.read_text())))
    print(f"wrote {HEADER_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
